import { Link, useNavigate } from "react-router-dom";

function Result() {
  const navigate = useNavigate();

  const savedSymptoms = JSON.parse(
    localStorage.getItem("selectedSymptoms") || "[]"
  );

  const savedPrediction = JSON.parse(
    localStorage.getItem("predictionResult") || "null"
  );

  // ==========================================
  // CHECK IF PREDICTION EXISTS
  // ==========================================

  if (savedSymptoms.length === 0 || !savedPrediction) {
    return (
      <main className="result-page">
        <div className="no-result">
          <div className="empty-symbol">?</div>

          <h1>No Prediction Available</h1>

          <p>
            Please select symptoms before viewing a prediction.
          </p>

          <Link to="/prediction" className="btn primary-btn">
            Start Prediction
          </Link>
        </div>
      </main>
    );
  }

  // ==========================================
  // REAL ML PREDICTION
  // ==========================================

  const prediction = {
    disease: savedPrediction.disease,
    confidence: savedPrediction.confidence,
    description:
      "This prediction was generated by the Random Forest machine learning model based on the symptoms you selected.",
  };

  // ==========================================
  // SAVE TO HISTORY
  // ==========================================

  const saveHistory = () => {
    const history = JSON.parse(
      localStorage.getItem("predictionHistory") || "[]"
    );

    const record = {
      id: Date.now(),
      disease: prediction.disease,
      confidence: prediction.confidence,
      symptoms: savedSymptoms,
      date: new Date().toLocaleString(),
    };

    localStorage.setItem(
      "predictionHistory",
      JSON.stringify([record, ...history])
    );

    alert("Prediction saved to history.");
  };

  return (
    <main className="result-page">

      <div className="result-container">

        {/* ==========================================
            HEADING
        ========================================== */}

        <div className="result-heading">

          <span className="section-label">
            STEP 02 — ANALYSIS COMPLETE
          </span>

          <h1>Your Prediction Result</h1>

          <p>
            Here is the estimated result based on your selected symptoms.
          </p>

        </div>


        {/* ==========================================
            RESULT CARD
        ========================================== */}

        <section className="result-card">

          <div className="result-top">

            <div className="result-icon">
              ✓
            </div>

            <div>

              <span className="result-label">
                ESTIMATED CONDITION
              </span>

              <h2>
                {prediction.disease}
              </h2>

              <p>
                {prediction.description}
              </p>

            </div>

          </div>


          {/* ==========================================
              CONFIDENCE
          ========================================== */}

          <div className="confidence-section">

            <div className="confidence-header">

              <span>
                Prediction Confidence
              </span>

              <strong>
                {prediction.confidence}%
              </strong>

            </div>


            <div className="confidence-bar">

              <div
                style={{
                  width: `${prediction.confidence}%`,
                }}
              ></div>

            </div>

          </div>


          <div className="result-divider"></div>


          {/* ==========================================
              SELECTED SYMPTOMS
          ========================================== */}

          <div className="result-symptoms">

            <h3>
              Selected Symptoms
            </h3>

            <div className="result-tags">

              {savedSymptoms.map((symptom) => (

                <span key={symptom}>
                  ✓ {symptom}
                </span>

              ))}

            </div>

          </div>


          {/* ==========================================
              ACTIONS
          ========================================== */}

          <div className="result-actions">

            <button
              className="btn primary-btn"
              onClick={saveHistory}
            >
              Save to History
            </button>


            <button
              className="btn secondary-btn"
              onClick={() => navigate("/prediction")}
            >
              Try Again
            </button>

          </div>

        </section>


        {/* ==========================================
            DISCLAIMER
        ========================================== */}

        <div className="result-disclaimer">

          <strong>
            ⚠️ Important
          </strong>

          <p>
            This result is generated by an academic machine
            learning model and is not a medical diagnosis.
            Do not use this result to make medical decisions.
            Please consult a qualified healthcare professional.
          </p>

        </div>

      </div>

    </main>
  );
}

export default Result;